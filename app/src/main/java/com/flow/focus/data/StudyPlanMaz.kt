    fun tasks(now: Long): List<Task> {
        val list = rows.map { (day, slot, title) ->
            val dur = when {
                slot == 6 -> 135
                slot == 12 -> 60
                else -> 75
            }
            val isEvent = title.startsWith("کلاس") || title.startsWith("آزمون") || title.startsWith("شرکت")
            Task(
                id = "maz1405-d$day-s$slot",
                title = title,
                dueDay = start.plusDays(day.toLong()).toEpochDay(),
                dueMinute = slotStart[slot - 1],
                categoryId = "study",
                estimatedPomodoros = (dur / 25).coerceAtLeast(1),
                createdAt = now,
                kind = if (isEvent) ActivityKind.EVENT else ActivityKind.PLAN,
                durationMin = dur,
            )
        }
        val finalDay = start.plusDays(12).toEpochDay()
        return list + listOf(
            Task("maz1405-d12-exam", "آزمون ماز", dueDay = finalDay, dueMinute = 360, categoryId = "study", createdAt = now, kind = ActivityKind.EVENT, durationMin = 570, priority = Priority.HIGH),
            Task("maz1405-d12-review", "تحلیل آزمون ماز", dueDay = finalDay, dueMinute = 930, categoryId = "study", createdAt = now, kind = ActivityKind.EVENT, durationMin = 510),
        )
    }
